const { open, shot, elShot, note, BASE, S } = require(process.env.S + '/lib.js');
const { card, stateOf, upload, waitState } = require(process.env.S + '/cards.js');
const F = S + '/files/';
(async () => {
  let { browser, ctx, page } = await open({ storage: S + '/applicant.json' });
  page.on('response', (r) => { if (/submit/.test(r.url())) note(`${r.request().method()} ${r.url().replace(/^.*\/api/, '/api')} -> ${r.status()}`); });
  await page.goto(BASE + '/health/applications/new/step/3', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(3000);
  const land = card(page, 'สำเนาเอกสารสิทธิ์ที่ดิน');
  await upload(page, land, F + 'land_deed--correct-text.pdf');
  const cons = page.locator('div.rounded-xl.border-2').filter({ hasText: /ยินยอม/ }).first();
  await upload(page, cons, F + 'truncated-corrupt.pdf');
  const r1 = await waitState(page, land, ['checked-ok', 'checked-flags', 'check-failed']);
  const r2 = await waitState(page, cons, ['checked-ok', 'checked-flags', 'check-failed'], 240000);
  note(`re-upload: land=${r1.s} consent=${r2.s}`);
  await shot(page, '27-step3-reuploaded', { full: true });
  await page.goto(BASE + '/health/applications/new/step/2', { waitUntil: 'networkidle' }); await page.waitForTimeout(3000);
  await shot(page, '28-step2-flagged-slots-before-submit', { full: true });
  await page.goto(BASE + '/health/applications/new/step/6', { waitUntil: 'networkidle' }); await page.waitForTimeout(3000);
  const boxes = page.locator('input[type=checkbox]'); const n = await boxes.count();
  for (let i = 0; i < n; i++) await boxes.nth(i).check();
  const submit = page.getByRole('button', { name: 'ยื่นคำขอ' });
  note('submit enabled with flagged id_house_reg (unacknowledged) + FAILED consent: ' + await submit.isEnabled());
  await elShot(submit, '29-submit-enabled');
  await submit.click();
  await page.waitForTimeout(8000); await page.waitForLoadState('networkidle');
  note('after submit url ' + page.url());
  await shot(page, '30-after-submit', { full: true });
  await ctx.storageState({ path: S + '/applicant.json' });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
