const { open, shot, elShot, note, BASE, S } = require(process.env.S + '/lib.js');
const { card, stateOf } = require(process.env.S + '/cards.js');
const JUR = 'สำเนาหนังสือรับรองการจดทะเบียนนิติบุคคล';
(async () => {
  let { browser, ctx, page } = await open({ storage: S + '/applicant.json' });
  page.on('response', (r) => { if (/prechecks/.test(r.url())) note(`${r.request().method()} ${r.url().replace(/^.*\/api/, '/api')} -> ${r.status()}`); });
  await page.goto(BASE + '/health/applications/new/step/2', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(3000);
  const jur = card(page, JUR);
  const confirm = jur.getByRole('button', { name: 'ยืนยันว่าเอกสารถูกต้อง' });
  note('confirm enabled before press: ' + await confirm.isEnabled());
  await confirm.click();
  await page.waitForTimeout(2500);
  note('confirm enabled after press: ' + await confirm.isEnabled() + ' ; ack text: ' + (await jur.getByRole('status').allInnerTexts()).join('|'));
  await elShot(jur, '23-jur-acknowledged');
  await page.reload({ waitUntil: 'networkidle' }); await page.waitForTimeout(3000);
  const j2 = card(page, JUR);
  note('after reload: confirm enabled=' + await j2.getByRole('button', { name: 'ยืนยันว่าเอกสารถูกต้อง' }).isEnabled() + ' status=' + (await j2.getByRole('status').allInnerTexts()).join('|'));
  await elShot(j2, '23-jur-acknowledged-after-reload');
  await browser.close();
  ({ browser, ctx, page } = await open({ storage: S + '/applicant.json', dark: true }));
  await page.goto(BASE + '/health/applications/new/step/2', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(3000);
  await elShot(card(page, JUR), '23-jur-acknowledged-dark');
  await browser.close();
  // step 6: flagged slot visible + submit enabled
  ({ browser, ctx, page } = await open({ storage: S + '/applicant.json' }));
  await page.goto(BASE + '/health/applications/new/step/6', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(3000);
  const submit = page.getByRole('button', { name: 'ยื่นคำขอ' });
  note('step6 submit enabled before declarations: ' + await submit.isEnabled());
  const boxes = page.locator('input[type=checkbox]'); const n = await boxes.count();
  for (let i = 0; i < n; i++) await boxes.nth(i).check();
  await page.waitForTimeout(1500);
  note(`step6 checked ${n} declarations; submit enabled: ${await submit.isEnabled()}`);
  note('step6 flagged blocks visible: ' + await page.locator('[data-precheck="checked-flags"]').count() + ' ; any precheck text: ' + await page.getByText('ข้อสังเกตจากการตรวจเบื้องต้น').count());
  await shot(page, '24-step6-review-submit-enabled', { full: true });
  await ctx.storageState({ path: S + '/applicant.json' });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
