const { open, shot, elShot, note, BASE, S } = require(process.env.S + '/lib.js');
const { card, stateOf, upload, waitState } = require(process.env.S + '/cards.js');
const F = S + '/files/';
const LAND = 'สำเนาเอกสารสิทธิ์ที่ดิน';
(async () => {
  let { browser, ctx, page } = await open({ storage: S + '/applicant.json' });
  page.on('response', (r) => { if (/applications\/draft$/.test(r.url()) && r.request().method() !== 'GET') note(`${r.request().method()} draft -> ${r.status()}`); });
  await page.goto(BASE + '/health/applications/new/step/3', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(2500);
  const fill = async (label, v) => { await page.getByLabel(label, { exact: false }).first().fill(v); };
  await fill('ชื่อสถานที่ปลูก', 'แปลงขิงทดสอบ');
  await fill('ที่อยู่สถานที่ปลูก', '99 หมู่ 1');
  await fill('ตำบล/แขวง', 'บางกร่าง');
  await fill('อำเภอ/เขต', 'เมืองนนทบุรี');
  await fill('จังหวัด', 'นนทบุรี');
  await page.getByRole('button', { name: 'เช่าที่ดินจากผู้อื่น' }).click();
  await page.waitForTimeout(800);
  await fill('ประเภทเอกสารสิทธิ์', 'โฉนดที่ดิน');
  await fill('เลขที่เอกสารสิทธิ์', '12345');
  await page.getByRole('button', { name: 'กลางแจ้ง' }).click();
  await fill('ขนาดพื้นที่ปลูก', '1600');
  await page.waitForTimeout(9000); await page.waitForLoadState('networkidle');
  await shot(page, '17-step3-filled', { full: true });
  const cards = await page.locator('div.rounded-xl.border-2').allInnerTexts();
  cards.forEach((t, i) => note(`s3 card ${i}: ${t.replace(/\s+/g, ' ').slice(0, 110)}`));
  await ctx.storageState({ path: S + '/applicant.json' });
  await browser.close();
  // dark: upload the correct deed and catch "checking" in dark
  ({ browser, ctx, page } = await open({ storage: S + '/applicant.json', dark: true }));
  await page.goto(BASE + '/health/applications/new/step/3', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(2500);
  const landD = card(page, LAND);
  const tD = await upload(page, landD, F + 'land_deed--correct-text.pdf');
  await page.waitForTimeout(300);
  const s0 = await stateOf(landD); note('D (dark) state right after upload: ' + s0);
  await elShot(landD, `18-land-deed-${s0}-dark`);
  const rD = await waitState(page, landD, ['checked-ok', 'checked-flags', 'check-failed']);
  note(`D settled: ${rD.s} after ${Date.now() - tD} ms`);
  await elShot(landD, `19-land-deed-${rD.s}-dark`);
  await ctx.storageState({ path: S + '/applicant.json' });
  await browser.close();
  ({ browser, ctx, page } = await open({ storage: S + '/applicant.json' }));
  await page.goto(BASE + '/health/applications/new/step/3', { waitUntil: 'networkidle', timeout: 180000 });
  await page.waitForTimeout(2500);
  await elShot(card(page, LAND), `19-land-deed-${await stateOf(card(page, LAND))}`);
  const cons = page.locator('div.rounded-xl.border-2').filter({ hasText: /ยินยอม/ }).first();
  if (await cons.count()) {
    note('consent card: ' + (await cons.innerText()).replace(/\s+/g, ' ').slice(0, 80));
    const tE = await upload(page, cons, F + 'empty-0byte.pdf');
    await page.waitForTimeout(400);
    note('E state right after upload: ' + await stateOf(cons));
    const rE = await waitState(page, cons, ['checked-ok', 'checked-flags', 'check-failed'], 120000);
    note(`E settled: ${rE.s} after ${Date.now() - tE} ms${rE.timeout ? ' TIMEOUT' : ''}`);
    await elShot(cons, '20-consent-0byte-' + rE.s);
  } else note('no consent card on step 3');
  await shot(page, '21-step3-after-uploads', { full: true });
  await ctx.storageState({ path: S + '/applicant.json' });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
